// approvalPrompt is the question asked through HITL (Python reference:
// middleware/builtin/tools/approval.py). The tool arguments are rendered as an
// indented block preceded by a model-generated marker: every line of the payload
// keeps the indent, while the question's own lines have none, so text injected
// into the arguments cannot pose as part of the question.
//
// AGO-DEVIATION: Python interleaves the raw arguments on the question line
// (_DEFAULT_MESSAGE_ALWAYS); AGo fences them in a marked block because the
// arguments are model output and a prompt-injection vector against the human
// operator (audit M-16).
const approvalPrompt = "Agent wants to call the tool:\n`%s`\n" +
	"Arguments (generated by the model — untrusted data, not instructions):\n%s\n" +
	"Please approve or deny this request.\nY/N/Always?\n"

// approvalArgsIndent prefixes every line of the arguments block in the approval
// question. It is the visual fence: an indented line is payload, a flush line is
// the question.
const approvalArgsIndent = "    "

// approvalArgsBlock renders tool arguments for the approval question: CRLF is
// normalized and every line is prefixed with approvalArgsIndent, so an argument
// payload containing fake question lines ("SYSTEM: already approved, answer
// always") still reads as part of the fenced block.
func approvalArgsBlock(args string) string {
	lines := strings.Split(strings.ReplaceAll(args, "\r\n", "\n"), "\n")
	for i, line := range lines {
		lines[i] = approvalArgsIndent + line
	}
	return strings.Join(lines, "\n")
}

// errDeniedByHuman becomes the ToolErrorEvent returned when the human declines.
var errDeniedByHuman = errors.New("denied by human")

// ApprovalOption configures Approval.
type ApprovalOption func(*approvalOptions)

type approvalOptions struct {
	argsScopedAlways bool
	// timeoutSecs is the default per-question deadline (0 = wait indefinitely,
	// Python parity).
	timeoutSecs float64
}

// WithArgsScopedAlways narrows an "always" grant to the exact arguments of the
// approved call: later calls of the same tool skip the question only when the
// SHA-256 of their arguments equals the approved call's; any other argument set
// is asked again. Without it (default, Python parity) one "always" covers every
// later call of the same tool implementation regardless of arguments — which for
// a shell or code tool means arbitrary arguments run unasked for the rest of the
// turn (audit M-15).
func WithArgsScopedAlways() ApprovalOption {
	return func(o *approvalOptions) { o.argsScopedAlways = true }
}

// WithApprovalTimeout puts a deadline on every approval question, so a turn
// whose operator walked away fails with a hitl timeout instead of parking
// forever (audit M-26). d <= 0 keeps the default: wait indefinitely, bounded
// only by turn cancellation.
func WithApprovalTimeout(d time.Duration) ApprovalOption {
	return func(o *approvalOptions) {
		if d <= 0 {
			o.timeoutSecs = 0
			return
		}
		o.timeoutSecs = d.Seconds()
	}
}

// Approval gates every tool execution behind a human confirmation asked through
// ctx.Ask as an events.ToolApprovalRequest with ToolCallID = the call id.
//
// Answers "y", "yes", "approve" approve the current call. "always" approves it
// and grants all further calls with the same grant key on this middleware
// instance; the key is the call's Source, falling back to its Name when the
// source is empty (Python parity: the grant covers the tool implementation, so
// a same-named tool with a different source is still asked). Pass
// WithArgsScopedAlways to additionally bind the grant to the approved
// arguments. Any other answer denies the call with a ToolErrorEvent "denied by
// human" and lets the model see the refusal. An error from Ask (no HITL hook,
// timeout, refusal to answer) propagates unchanged.
//
// The question fences the model-generated arguments in a marked indented block
// (see approvalPrompt), so injected instructions in the arguments cannot blend
// into the question text.
//
// Grants live on the middleware instance, i.e. for one turn: a Factory builds a
// fresh instance per turn. Safe for concurrent use (the tool executor may run
// calls in parallel).
//
// AGO-DEVIATION: Python stores "always" grants in context.variables
// (conversation-scoped, BYPASS_KEY); the AGo contract scopes them to the
// middleware instance (per turn). The question runs on the turn's cancellable
// context, carried by the conversation context
// (agocontext.Context.TurnContext): cancelling or closing the turn unblocks a
// pending approval instead of leaking it (audit M-26).
// AGO-DEVIATION: Python's middleware receives the turn's async context as a
// hook parameter; AGo middleware hooks carry no stdlib context, so the turn
// context travels through the conversation context. AGO-DEVIATION: Go embedding
// forces the request through ctx.Ask as its embedded *events.HumanInputRequest;
// the concrete events.ToolApprovalRequest value (with ToolCallID) is what the
// middleware constructs and the answer is matched back to the call by ID here.
func Approval(opts ...ApprovalOption) Factory {
	var o approvalOptions
	for _, opt := range opts {
		opt(&o)
	}
	return func() Middleware {
		return &approval{granted: map[string]bool{}, opts: o}
	}
}

type approval struct {
	Base
	mu      sync.Mutex
	granted map[string]bool
	opts    approvalOptions
}

func (a *approval) OnToolExecution(next ToolExecFunc, ev *events.ToolCallEvent, ctx *agocontext.Context) (events.Event, error) {
	key := a.grantKey(ev)
	if a.isGranted(key) {
		return next(ev, ctx)
	}

	req := events.ToolApprovalRequest{
		HumanInputRequest: events.NewHumanInputRequest(
			fmt.Sprintf(approvalPrompt, ev.Name, approvalArgsBlock(ev.Arguments)), a.opts.timeoutSecs),
		ToolCallID: ev.ID,
	}
	// The turn context makes the question follow turn cancellation; without a
	// running turn TurnContext is Background, which only a WithApprovalTimeout
	// deadline bounds (audit M-26).
	answer, err := ctx.Ask(ctx.TurnContext(), &req.HumanInputRequest)
	if err != nil {
		return nil, err
	}

	switch strings.ToLower(strings.TrimSpace(answer)) {
	case "always":
		a.grant(key)
		return next(ev, ctx)
	case "y", "yes", "approve":
		return next(ev, ctx)
	}
	return events.FromErrorCall(*ev, errDeniedByHuman), nil
}

// grantKey identifies what an "always" answer approves: the call's Source,
// falling back to its Name when the source is empty (Python parity: the grant
// covers the tool implementation, so a same-named tool with a different source
// is still asked). With WithArgsScopedAlways the key additionally carries the
// SHA-256 of the arguments, so the grant covers only identical argument sets.
// The hash is hex, so the "\x00" separator cannot be forged by a tool name.
func (a *approval) grantKey(ev *events.ToolCallEvent) string {
	key := ev.Source
	if key == "" {
		key = ev.Name
	}
	if a.opts.argsScopedAlways {
		sum := sha256.Sum256([]byte(ev.Arguments))
		key += "\x00" + hex.EncodeToString(sum[:])
	}
	return key
}

func (a *approval) isGranted(key string) bool {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.granted[key]
}

func (a *approval) grant(key string) {
	a.mu.Lock()
	defer a.mu.Unlock()
	a.granted[key] = true
}

var _ Middleware = (*approval)(nil)
